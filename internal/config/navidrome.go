package config

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/pelletier/go-toml/v2"
)

// navidromeConfig mirrors the Navidrome options wn-server sets. Names match
// conf/configuration.go in Navidrome.
type navidromeConfig struct {
	Address     string
	Port        int
	MusicFolder string
	DataFolder  string
	ExtAuth     navidromeExtAuth

	EnableInsightsCollector bool
	EnableExternalServices  bool
}

type navidromeExtAuth struct {
	UserHeader     string
	TrustedSources string
}

// NavidromeDataDir is the folder Navidrome uses for its database and caches.
func (c *Config) NavidromeDataDir() string {
	return filepath.Join(c.DataDir, "navidrome")
}

// NavidromeConfigPath is where WriteNavidrome puts navidrome.toml.
func (c *Config) NavidromeConfigPath() string {
	return filepath.Join(c.DataDir, "navidrome.toml")
}

// RenderNavidrome returns the contents of navidrome.toml.
//
// Navidrome's config file has a single MusicFolder string and no list of
// libraries. Navidrome stores MusicFolder as the path of library 1 on every
// start, and library paths are unique. MusicFolder is therefore sorted_dir,
// which is created on load and never moves. Changing it with the list of
// music folders would collide with the libraries created through the API.
// The supervisor adds every music folder through Navidrome's API.
func (c *Config) RenderNavidrome() ([]byte, error) {
	body, err := toml.Marshal(navidromeConfig{
		Address:     "127.0.0.1",
		Port:        c.NavidromePort,
		MusicFolder: c.SortedDir,
		DataFolder:  c.NavidromeDataDir(),
		ExtAuth: navidromeExtAuth{
			UserHeader:     "Remote-User",
			TrustedSources: "127.0.0.1/32",
		},
		EnableInsightsCollector: false,
		EnableExternalServices:  c.ExternalServices(),
	})
	if err != nil {
		return nil, err
	}
	header := "# Generated by wn-server. Changes are overwritten.\n"
	return append([]byte(header), body...), nil
}

// WriteNavidrome renders navidrome.toml into the data directory and creates
// Navidrome's data folder.
func (c *Config) WriteNavidrome() error {
	body, err := c.RenderNavidrome()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(c.NavidromeDataDir(), 0o700); err != nil {
		return fmt.Errorf("create navidrome data folder: %w", err)
	}
	if err := os.WriteFile(c.NavidromeConfigPath(), body, 0o600); err != nil {
		return fmt.Errorf("write navidrome.toml: %w", err)
	}
	return nil
}
